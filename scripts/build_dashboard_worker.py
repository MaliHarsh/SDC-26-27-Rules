"""Create a single-file Worker suitable for Cloudflare's dashboard editor."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
worker = (root/'worker/index.js').read_text()
worker = '\n'.join(worker.splitlines()[2:])
shared = (root/'assets/rules-search.js').read_text()
validation = shared[shared.index('export function validCitations'):].replace('export function','function',1)
source = '// Generated by scripts/build_dashboard_worker.py. Do not edit this copy.\n'
source += 'const rules = ' + (root/'assets/rules.json').read_text().strip() + ';\n'
source += validation + '\n' + worker + '\n'
(root/'worker/dashboard-worker.js').write_text(source)
